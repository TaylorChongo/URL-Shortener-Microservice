def merge_duplicate_links() -> None:
    """Added by hand: the unique rule below fails if a user already has the same URL twice.

    For each group of duplicates, keep the most-clicked link (the oldest if tied), so a link
    that was already shared keeps working. Move the others' clicks, tags and alias onto it,
    add their click counts to it, then delete them.
    """
    connection = op.get_bind()

    duplicate_groups = connection.execute(
        sa.select(urls.c.user_id, urls.c.original_url)
        .group_by(urls.c.user_id, urls.c.original_url)
        .having(sa.func.count() > 1)
    ).all()

    for user_id, original_url in duplicate_groups:
        links = connection.execute(
            sa.select(urls.c.id, urls.c.click_count, urls.c.custom_alias)
            .where(urls.c.user_id == user_id, urls.c.original_url == original_url)
            .order_by(urls.c.click_count.desc(), urls.c.id)
        ).all()
        keeper = links[0]
        others = links[1:]
        other_ids = [link.id for link in others]

        # 1. move the visits and add their counts
        connection.execute(clicks.update().where(clicks.c.url_id.in_(other_ids)).values(url_id=keeper.id))
        extra_clicks = sum(link.click_count for link in others)
        connection.execute(
            urls.update().where(urls.c.id == keeper.id).values(click_count=urls.c.click_count + extra_clicks)
        )

        # 2. give the kept link any tag the others had
        keeper_tags = set(connection.scalars(sa.select(url_tags.c.tag_id).where(url_tags.c.url_id == keeper.id)))
        other_tags = set(connection.scalars(sa.select(url_tags.c.tag_id).where(url_tags.c.url_id.in_(other_ids))))
        for tag_id in other_tags - keeper_tags:
            connection.execute(url_tags.insert().values(url_id=keeper.id, tag_id=tag_id))

        # 3. delete the others (their url_tags rows go with them: ON DELETE CASCADE)
        connection.execute(urls.delete().where(urls.c.id.in_(other_ids)))

        # 4. if the kept link has no alias but another one had, keep that alias working
        other_aliases = [link.custom_alias for link in others if link.custom_alias is not None]
        if keeper.custom_alias is None and other_aliases:
            connection.execute(urls.update().where(urls.c.id == keeper.id).values(custom_alias=other_aliases[0]))


